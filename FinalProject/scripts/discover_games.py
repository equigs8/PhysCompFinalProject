#!/usr/bin/env python3
"""
PlatformIO pre-build script that auto-discovers game folders inside src/games/
and regenerates src/games/GameList.h automatically.

How it works:
  - Scans every direct subfolder of FinalProject/src/games/
  - Skips folders named 'template', starting with '_' or '.', or containing a '.disabled' file
  - Finds header files (*.h / *.hpp) declaring `class <Name> : public sdk::Game`
  - Updates src/games/GameList.h only when the discovered set changes (preserves fast incremental builds)

Result:
  Drop a game folder into src/games/ -> it automatically appears in the Main Menu.
  Remove a game folder from src/games/ -> it automatically disappears from the Main Menu.
"""

import os
import re
import sys

GAME_CLASS_RE = re.compile(
    r"\bclass\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?:final\s*)?:\s*public\s+(?:sdk::)?Game\b"
)

# Preferred ordering for built-in games (if present); all other games sort alphabetically after
PREFERRED_ORDER = ["tictactoe", "pokemon", "chess", "snake", "star_blaster"]
IGNORED_FOLDERS = {"template"}


def sort_key(folder_name: str):
    low = folder_name.lower()
    if low in PREFERRED_ORDER:
        return (0, PREFERRED_ORDER.index(low), low)
    return (1, 0, low)


def strip_cpp_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def discover_games(games_dir: str):
    discovered = []
    excluded_folders = []
    seen_classes = {}

    if not os.path.isdir(games_dir):
        return discovered, excluded_folders

    entries = [
        name for name in os.listdir(games_dir)
        if os.path.isdir(os.path.join(games_dir, name))
    ]
    entries.sort(key=sort_key)

    for folder in entries:
        folder_path = os.path.join(games_dir, folder)
        if (
            folder.startswith(".")
            or folder.startswith("_")
            or folder.lower() in IGNORED_FOLDERS
            or os.path.exists(os.path.join(folder_path, ".disabled"))
        ):
            excluded_folders.append(folder)
            continue

        header_files = sorted(
            f for f in os.listdir(folder_path)
            if f.endswith((".h", ".hpp")) and os.path.isfile(os.path.join(folder_path, f))
        )

        for header in header_files:
            header_path = os.path.join(folder_path, header)
            try:
                with open(header_path, "r", encoding="utf-8", errors="ignore") as f:
                    content = strip_cpp_comments(f.read())
            except OSError:
                continue

            for match in GAME_CLASS_RE.finditer(content):
                cls_name = match.group(1)
                rel_include = f"{folder}/{header}"
                if cls_name in seen_classes:
                    print(
                        f"[GameDiscovery] WARNING: Duplicate class '{cls_name}' in "
                        f"'{rel_include}' (already found in '{seen_classes[cls_name]}'). Skipping."
                    )
                    continue
                seen_classes[cls_name] = rel_include
                discovered.append((folder, rel_include, cls_name))

    return discovered, excluded_folders


def generate_game_list(project_dir: str):
    games_dir = os.path.join(project_dir, "src", "games")
    output_path = os.path.join(games_dir, "GameList.h")

    discovered, excluded_folders = discover_games(games_dir)

    lines = [
        "#pragma once",
        "",
        "// ==============================================================================",
        "// AUTO-GENERATED BY scripts/discover_games.py -- DO NOT EDIT MANUALLY",
        "// ==============================================================================",
        "// Add any game folder under src/games/<my_game>/ (with a class inheriting",
        "// from sdk::Game) and build -> it will automatically appear in the Main Menu.",
        "// Remove the folder (or add a .disabled file inside it) to remove it.",
        "",
        '#include "../sdk/GameRegistry.h"',
        "",
    ]

    for _, rel_include, _ in discovered:
        lines.append(f'#include "{rel_include}"')

    lines.extend([
        "",
        "inline void registerAllGames() {",
    ])

    for idx, (_, _, cls_name) in enumerate(discovered):
        var_name = f"gameInstance_{idx}"
        lines.append(f"  static {cls_name} {var_name};")
        lines.append(f"  sdk::GameRegistry::registerGame(&{var_name});")

    lines.extend([
        "}",
        "",
    ])

    new_content = "\n".join(lines)

    old_content = None
    if os.path.isfile(output_path):
        try:
            with open(output_path, "r", encoding="utf-8") as f:
                old_content = f.read()
        except OSError:
            old_content = None

    if old_content != new_content:
        with open(output_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(new_content)
        names = ", ".join(cls for _, _, cls in discovered) or "(none)"
        print(f"[GameDiscovery] Updated src/games/GameList.h ({len(discovered)} games: {names})")
    else:
        names = ", ".join(cls for _, _, cls in discovered) or "(none)"
        print(f"[GameDiscovery] {len(discovered)} games ready: {names}")

    return excluded_folders


# PlatformIO SCons hook
try:
    Import("env")  # type: ignore  # noqa: F821
    project_dir = env.subst("$PROJECT_DIR")  # type: ignore  # noqa: F821
    excluded = generate_game_list(project_dir)
    if excluded:
        base_filters = list(env.get("SRC_FILTER") or ["+<*>", "-<.git/>", "-<.svn/>"])
        for folder in excluded:
            base_filters.append(f"-<games/{folder}/>")
        env.Replace(SRC_FILTER=base_filters)  # type: ignore  # noqa: F821
except NameError:
    if __name__ == "__main__":
        script_dir = os.path.dirname(os.path.abspath(__file__))
        default_project_dir = os.path.dirname(script_dir)
        target_dir = sys.argv[1] if len(sys.argv) > 1 else default_project_dir
        generate_game_list(target_dir)
